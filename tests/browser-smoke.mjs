import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { existsSync, mkdirSync } from 'node:fs';
const baseURL = process.env.BASE_URL || 'http://127.0.0.1:4173';
const artifactDir = process.env.ARTIFACT_DIR || '/tmp/clinic-browser-artifacts';
mkdirSync(artifactDir, { recursive: true });
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || (existsSync('/usr/bin/chromium') ? '/usr/bin/chromium' : chromium.executablePath()), headless:true, args:['--no-sandbox'] });
const context = await browser.newContext({ viewport: { width:390, height:844 }, timezoneId:'America/Sao_Paulo', reducedMotion:'reduce' });
const page = await context.newPage();
await page.clock.install({time:new Date('2026-11-09T15:00:00Z')});
let galleryFailure = true, loggedIn = false, appointmentFailed = true;
const pageErrors=[];
page.on('pageerror', error => pageErrors.push(error.message));
await page.route('**/*', async route => {
  const url = new URL(route.request().url());
  if (url.origin !== new URL(baseURL).origin) return route.abort();
  if (!url.pathname.startsWith('/api/')) return route.continue();
  const path=url.pathname, method=route.request().method();
  const reply=(status,body)=>route.fulfill({status, contentType:'application/json',body:JSON.stringify(body)});
  if(path==='/api/check-auth') return reply(loggedIn?200:401,{isAuthenticated:loggedIn});
  if(path==='/api/login') { if(route.request().postDataJSON().password==='wrong')return reply(401,{message:'Credenciais inválidas'}); loggedIn=true; return reply(200,{success:true}); }
  if(path==='/api/logout') { loggedIn=false;return reply(200,{success:true}); }
  if(path==='/api/massagistas') return galleryFailure?reply(503,{message:'Indisponível'}):reply(200,{massagistas:[{id:1,nome:'Profissional Teste',descricao:'Descrição de teste',fotoUrl:'/broken-image.jpg',ativa:true,suiteMaster:false}]});
  if(path==='/api/appointments' && method==='GET') return reply(503,{message:'Indisponível'});
  if(path==='/api/appointments' && method==='POST') { if(appointmentFailed)return reply(503,{message:'Tente novamente em instantes.'});return reply(201,{success:true,appointment:{id:1,referralCode:'TESTE123'}}); }
  return reply(404,{message:'Rota desconhecida'});
});
await page.goto(baseURL + '/');
await page.getByText('Erro ao carregar profissionais.',{exact:false}).waitFor();
galleryFailure=false;
await page.getByRole('button',{name:'Tentar novamente',exact:true}).click();
await page.getByRole('heading',{name:'Profissional Teste'}).waitFor();
await page.getByRole('button',{name:'Abrir menu'}).click();
assert.equal(await page.getByRole('button',{name:'Fechar menu'}).getAttribute('aria-expanded'),'true');
await page.getByRole('link',{name:'Contato',exact:true}).first().click();
await page.getByRole('button',{name:'Confirmar Agendamento',exact:true}).click();
await page.getByText('Informe um telefone com DDD e 10 ou 11 dígitos.').waitFor();
await page.getByLabel('Nome Completo').fill('Cliente Teste');
await page.getByLabel('Telefone/WhatsApp').fill('(83) 99999-1234');
await page.getByRole('combobox').first().click();
await page.getByRole('option').first().click();
await page.getByText('Selecione uma data',{exact:true}).click();
await page.getByRole('button',{name:'Próximo mês'}).click();
await page.getByRole('gridcell',{name:'5',exact:true}).click(); // Saturday, December 5
await page.keyboard.press('Escape');
await page.getByRole('combobox').nth(1).click();
assert.equal(await page.getByRole('option',{name:'08:30',exact:true}).count(),0);
await page.getByRole('option',{name:'09:00',exact:true}).click();
await page.getByRole('button',{name:'Confirmar Agendamento',exact:true}).click();
await page.getByText('Tente novamente em instantes.').first().waitFor();
assert.equal(await page.getByLabel('Nome Completo').inputValue(),'Cliente Teste');
appointmentFailed=false;
await page.getByRole('button',{name:'Confirmar Agendamento',exact:true}).click();
await page.getByRole('dialog').getByText('TESTE123',{exact:true}).waitFor();
await page.keyboard.press('Escape');
assert.equal(await page.getByLabel('Nome Completo').inputValue(),'');
assert.equal(await page.getByRole('combobox').first().innerText(),'Selecione um serviço');
assert.equal(await page.getByRole('combobox').nth(1).innerText(),'Selecione um horário');
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Mobile overflow');
await page.screenshot({path:`${artifactDir}/clinic-mobile.png`,fullPage:true});
await page.goto(baseURL + '/login');
await page.getByLabel('Usuário',{exact:true}).fill('tester');
await page.getByLabel('Senha',{exact:true}).fill('wrong');
await page.getByRole('button',{name:'Entrar',exact:true}).click();
await page.getByText('Credenciais inválidas').first().waitFor();
await page.getByLabel('Senha',{exact:true}).fill('right');
await page.getByRole('button',{name:'Entrar',exact:true}).click();
await page.waitForURL('**/admin');
await page.getByRole('alert').filter({hasText:'Não foi possível carregar'}).waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Admin mobile overflow');
await page.screenshot({path:`${artifactDir}/clinic-admin-mobile.png`,fullPage:true});
await page.getByRole('button',{name:'Sair',exact:true}).click();
await page.waitForURL('**/login');
await page.setViewportSize({width:1440,height:1000});
await page.goto(baseURL + '/');
await page.getByRole('heading',{name:'Profissional Teste'}).waitFor();
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true,'Desktop overflow');
await page.screenshot({path:`${artifactDir}/clinic-desktop.png`,fullPage:true});
assert.deepEqual(pageErrors,[]);
console.log('PASS: gallery retry, mobile navigation, invalid phone, weekend schedule, booking failure/retry/reset, login failure/success, admin API error, logout, mobile/desktop overflow; no uncaught JS errors.');
await browser.close();
